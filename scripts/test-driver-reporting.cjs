const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const { PGlite } = require('../.fleet-preview/node_modules/@electric-sql/pglite');
const { createDriverReportingHandler } = require('../supabase/functions/data-api/driver-reporting.mjs');
const migration = fs.readFileSync(path.join(__dirname,'../supabase/migrations/20261113010000_driver_reporting.sql'),'utf8');
const ids={dealer:'10000000-0000-4000-8000-000000000001',other:'10000000-0000-4000-8000-000000000002',driver:'20000000-0000-4000-8000-000000000001',second:'20000000-0000-4000-8000-000000000002',third:'20000000-0000-4000-8000-000000000003'};

async function makeDatabase() {
  const db=new PGlite();
  await db.exec(`create role anon; create role authenticated; create role service_role;
    create table public.insurance_partners(id uuid primary key,name text,partner_type text,active boolean,frontend_permissions jsonb default '{}');
    create table public.drivers(id uuid primary key,name text,dealer_partner_id uuid,fleet_name text,driver_status text default '待上線');
    insert into insurance_partners values('${ids.dealer}','亞菲得股份有限公司','dealer',true,'{}'),('${ids.other}','其他車商','dealer',true,'{}');
    insert into drivers(id,name,dealer_partner_id,fleet_name) values('${ids.driver}','測試司機一','${ids.dealer}',null),('${ids.second}','測試司機二','${ids.dealer}',null),('${ids.third}','未開放司機','${ids.other}',null);`);
  await db.exec(migration);
  return db;
}

async function run() {
  const app=fs.readFileSync(path.join(__dirname,'../app.js'),'utf8');
  const start=app.indexOf('  function reportingEnabledForDealer('),end=app.indexOf('\n  function ',start+10);
  const enabled=vm.runInNewContext(app.slice(start,end)+';reportingEnabledForDealer');
  const a={name:'亞菲得股份有限公司',partner_type:'dealer',active:true};
  assert.equal(enabled(a),true);assert.equal(enabled({...a,active:false}),false);
  assert.equal(enabled({...a,frontend_permissions:{driverReporting:false}}),false);
  assert.equal(enabled({...a,frontend_permissions:{driverReporting:'true'}}),false);
  assert.equal(enabled({...a,frontend_permissions:{driverReporting:null}}),false);
  assert.equal(enabled({...a,name:'其他車商'}),false);
  assert.equal(enabled({...a,name:'其他車商',frontend_permissions:{driverReporting:true}}),false);
  assert.equal(enabled({...a,partner_type:'broker'}),false);
  console.log('PASS: supplier frontend switch defaults and explicit permission values.');
  const db=await makeDatabase();
  try {
    const now=(await db.query("select to_char((clock_timestamp() at time zone 'Asia/Taipei')::date,'YYYY-MM-DD') as day")).rows[0].day;
    const month=now.slice(0,7), m=month+'-01', actor={id:'super-admin',name:'督導測試',role:'admin'};
    const query=async(sql,args=[]) => (await db.query(sql,args)).rows[0]?.result;
    const load=driver=>query('select public.driver_reporting_load($1,$2) as result',[m,driver]);
    const save=(config,revision=0)=>query('select public.driver_reporting_save_month($1,$2,$3,$4) as result',[m,JSON.stringify(config),revision,JSON.stringify(actor)]);
    const submit=(driver,dates,revision=1)=>query('select public.driver_reporting_submit($1,$2,$3,$4) as result',[m,driver,dates,revision]);
    const config={is_open:true,opens_on:now,closes_on:now,allowed_days:4,blocked_dates:[month+'-09']};
    await assert.rejects(load(ids.third),/尚未開放/);
    assert.equal((await load(null)).rows.length,2,'only eligible drivers are listed before submissions');
    await db.query("update drivers set driver_status='已離職' where id=$1",[ids.second]);
    await assert.rejects(load(ids.second),/尚未開放/);
    assert.equal((await load(null)).rows.length,1);
    await db.query("update drivers set driver_status='待上線' where id=$1",[ids.second]);
    await save(config);
    await assert.rejects(save(config),/已更新/);
    await assert.rejects(submit(ids.driver,[month+'-09']),/禁休日/);
    await assert.rejects(submit(ids.driver,['1999-01-01']),/非本月/);
    await assert.rejects(submit(ids.driver,[month+'-01',month+'-01']),/重複/);
    await assert.rejects(submit(ids.driver,[null]),/空白/);
    await assert.rejects(submit(ids.driver,[],0),/設定已變更/);
    await db.exec(`update insurance_partners set frontend_permissions='{"driverReporting":false}' where id='${ids.dealer}'`);
    await assert.rejects(submit(ids.driver,[]),/尚未開放/);
    await db.exec(`update insurance_partners set frontend_permissions='{}' where id='${ids.dealer}'`);
    const dates=[1,2,3,4,5].map(day=>month+'-'+String(day).padStart(2,'0'));
    const saved=await submit(ids.driver,dates);
    assert.equal(saved.status,'pending');assert.equal(saved.off_dates.length,5);assert.equal(saved.allowed_days,4);
    const mine=await load(ids.driver);assert.equal(mine.rows.length,1);assert.equal(mine.rows[0].driver_id,ids.driver);assert.equal(mine.audit.length,0);
    await assert.rejects(submit(ids.driver,[]),/已送出/);
    await assert.rejects(save({...config,blocked_dates:[month+'-01']},1),/重疊/);
    assert.equal((await load(null)).config.revision,1);
    const review=(id,status,reason,revision=1)=>query('select public.driver_reporting_review($1,$2,$3,$4,$5) as result',[id,status,reason,revision,JSON.stringify(actor)]);
    await assert.rejects(review(saved.id,'rejected',''),/原因/);
    const approved=await review(saved.id,'approved','確認超額休假');assert.equal(approved.status,'approved');assert.equal(approved.reviewer_name,'督導測試');
    await assert.rejects(review(saved.id,'rejected','改動'),/已審核/);
    const raced=await Promise.allSettled([submit(ids.second,[]),submit(ids.second,[])]);
    assert.equal(raced.filter(item=>item.status==='fulfilled').length,1);
    const second=raced.find(item=>item.status==='fulfilled').value;
    await review(second.id,'rejected','人力不足，請聯繫督導');
    await assert.rejects(submit(ids.second,[month+'-06']),/已送出/);
    const audit=(await load(null)).audit;assert(audit.some(row=>row.action==='approved'));assert(audit.some(row=>row.action==='rejected'));assert(audit.some(row=>row.action==='month_settings'));
    await save({...config,is_open:false},1);
    await assert.rejects(submit(ids.third,[] ,2),/開放期間/);
    await db.exec(`update insurance_partners set frontend_permissions='{"driverReporting":true}' where id='${ids.other}'`);
    await assert.rejects(load(ids.third),/尚未開放/,'other dealers stay ineligible even after opt-in');
    await save({...config,opens_on:'2099-01-01',closes_on:'2099-01-31'},2);
    await assert.rejects(submit(ids.third,[],3),/開放期間/);
    await db.exec('set role authenticated');
    await assert.rejects(load(null),/permission denied/);
    await assert.rejects(db.query('select * from driver_reporting_submissions'),/permission denied/);
    await db.exec('reset role; set role service_role');
    assert.equal((await load(null)).rows.length,2);
    await assert.rejects(db.query('delete from driver_reporting_submissions'),/permission denied/);
    await db.exec('reset role');
    console.log('PASS: database migration, default dealer access, opt-in/out, blocked dates, month boundaries, stale settings, duplicate submits, over-quota review, locked submissions, immutable history, audit and role isolation.');
    const calls=[];
    const handler=createDriverReportingHandler({db:{rpc:async(name,args)=>{calls.push({name,args});return {data:{ok:true}};}},adminCan:async(s,p)=>s.allowed&&p==='driverReporting'});
    const driver={session_type:'driver',driver_id:ids.driver};
    assert.equal((await handler({action:'save_driver_reporting_month',month},driver)).status,403);
    assert.equal((await handler({action:'load_driver_reporting',month},{session_type:'partner'})).status,403);
    assert.equal((await handler({action:'load_driver_reporting',month},{session_type:'admin',allowed:false})).status,403);
    await handler({action:'submit_driver_reporting',month,dates:[],driver_id:ids.third,revision:1,confirmed:true},driver);
    assert.equal(calls.at(-1).args.p_driver,ids.driver,'posted driver id cannot impersonate another driver');
    assert.equal((await handler({action:'submit_driver_reporting',month,dates:[],revision:1,confirmed:false},driver)).status,400);
    assert.equal((await handler({action:'submit_driver_reporting',month,dates:[],revision:1,confirmed:true},{session_type:'admin',allowed:true})).status,403);
    console.log('PASS: API permission checks and session-derived driver identity.');
  } finally {await db.close();}
}
module.exports={makeDatabase,ids};
if(require.main===module)run().catch(error=>{console.error(error);process.exitCode=1;});
